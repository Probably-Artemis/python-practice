"""
Objective: output the result of each of these comparisons: 5 is greater than 3, 5 is equal to 5.0, 10 is less than or equal to 9, and "apple" is not equal to "Apple". Then output the type of True.
"""

print(5 > 3) # True
print(5 == 5.0) # True. python compares values, and 5 and 5.0 are the same value.
print(10 <= 9) # False
print("apple" != "Apple") # True. string comparisons are case-sensitive.
print(type(True)) # <class 'bool'>