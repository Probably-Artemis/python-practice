"""
Objective: output the result of 17 / 5, then 17 // 5, then 17 % 5. Leave a comment next to each one explaining what the operator does.
"""

print(17 / 5) # regular division. returns 3.4
print(17 // 5) # floored division. divides, then rounds down to the nearest whole number. returns 3
print(17 % 5) # modulo. returns the remainder left over after dividing. returns 2

# together, // and % say "5 goes into 17 three times, with 2 left over."