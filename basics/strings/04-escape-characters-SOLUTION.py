"""
Objective: using one singular print statement, output the following two lines to the console exactly as shown, quotation marks included:
She said "hello" to me.
It's a nice day.
"""

print("She said \"hello\" to me.\nIt's a nice day.") # \" puts a double quote inside a double quoted string, and \n starts a new line.

# the apostrophe in It's needs no escaping, since single quotes inside double quotes don't conflict.